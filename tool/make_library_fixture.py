#!/usr/bin/env python3
"""Generate the Session Library's Dart fixture from real recordings.

The library's widget, golden and scan tests run under a plain `flutter test`,
where `dart_duckdb`'s native library is not linked and no `.duckdb` file can be
opened (SPEC.md §12) — so what an index row holds has to arrive as Dart
source. This reads each file the way the app does and writes, per file:

- the 12 `metadata` keys the index keeps (§5.1),
- every `Lap` row with its `Lap Time` / `Last Sector1` / `Last Sector2`, by
  the equality join `lapTableSql` uses (§8.3.1),
- the number of master-clock discontinuities, by the same scan as
  `discontinuityScanSql` (§5.2),
- the file's size in bytes.

Paths in the output are rewritten into LMU's default Windows folder (§5), so
the fixture never carries the machine it was generated on, and modification
times are left out: they belong to a copy of a file, not to the recording.

Usage (the three samples are git-ignored; the fourth file is the checked-in
trimmed fixture, a real second session at the same layout and class):
    python3 tool/make_library_fixture.py test/fixtures/session_library_samples.dart \\
        "samples/Autódromo José Carlos Pace_P_2026-07-22T02_43_34Z.duckdb" \\
        "samples/Circuit de Spa-Francorchamps_Q_2026-07-24T02_06_11Z.duckdb" \\
        "samples/Sebring International Raceway_R_2026-07-07T06_42_17Z.duckdb" \\
        test/fixtures/sebring_race_laps0_3.duckdb
"""

from __future__ import annotations

import os
import sys

try:
    import duckdb
except ImportError:  # pragma: no cover - a setup problem, not a logic one
    sys.exit("needs `pip install duckdb`")

LAPS = """
WITH _b AS (SELECT value AS lap_index, ts AS start_ts,
                   lead(ts) OVER (ORDER BY ts) AS end_ts FROM "Lap")
SELECT _b.lap_index, _b.start_ts, _b.end_ts,
       lt.value, s1.value, s2.value
FROM _b
LEFT JOIN "Lap Time" lt ON lt.ts = _b.end_ts
LEFT JOIN "Last Sector1" s1 ON s1.ts = _b.end_ts
LEFT JOIN "Last Sector2" s2 ON s2.ts = _b.end_ts
ORDER BY _b.lap_index
"""

GAPS = """
WITH _g AS (SELECT value AS v, row_number() OVER () AS i FROM "GPS Time"),
     _d AS (SELECT i, v - lag(v) OVER (ORDER BY i) AS dt FROM _g)
SELECT count(*) FROM _d WHERE dt IS NOT NULL AND abs(dt - 0.01) > 1e-9
"""

KEYS = [
    ("DriverName", "driverName"),
    ("SteamID", "steamId"),
    ("RecordingTime", "recordingTime"),
    ("SessionTime", "sessionTimeOfDay"),
    ("TrackName", "trackName"),
    ("TrackLayout", "trackLayout"),
    ("WeatherConditions", "weatherConditions"),
    ("CarName", "carName"),
    ("CarClass", "carClass"),
    ("Version", "version"),
]

SESSION_TYPES = {"Practice": "practice", "Qualify": "qualify", "Race": "race"}

LMU_FOLDER = (
    r"C:\Program Files (x86)\Steam\steamapps\common\Le Mans Ultimate"
    r"\UserData\Telemetry"
)


def dart_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
    return f"'{escaped}'"


def dart_double(value) -> str:
    # 0.0 means "not recorded" (§8.3.1); the model maps it to null itself, so
    # it is emitted as written rather than pre-cleaned here.
    return "null" if value is None else repr(float(value))


def describe(path: str) -> str:
    con = duckdb.connect(path, read_only=True)
    try:
        md = dict(con.execute("SELECT key, value FROM metadata").fetchall())
        laps = con.execute(LAPS).fetchall()
        gaps = con.execute(GAPS).fetchone()[0]
    finally:
        con.close()

    name = os.path.basename(path)
    lines = [
        "  SampleSession(",
        f"    path: {dart_string(LMU_FOLDER + chr(92) + name)},",
        f"    sizeBytes: {os.path.getsize(path)},",
        f"    clockGapCount: {gaps},",
        "    metadata: SessionMetadata(",
        f"      sessionType: SessionType.{SESSION_TYPES[md['SessionType']]},",
    ]
    for key, field in KEYS:
        lines.append(f"      {field}: {dart_string(md.get(key, ''))},")
    lines += [
        "      // The setup blob is ~20 kB and nothing in the library reads it.",
        "      carSetupJson: '{}',",
        "    ),",
        "    laps: [",
    ]
    for index, start, end, time, s1, s2 in laps:
        lines.append(
            f"      ({index}, {dart_double(start)}, {dart_double(end)}, "
            f"{dart_double(time)}, {dart_double(s1)}, {dart_double(s2)}),"
        )
    lines += ["    ],", "  )"]
    return "\n".join(lines)


HEADER = """\
// Four real recordings as the Session Library indexes them (SPEC.md §8.1,
// §9.6). GENERATED by tool/make_library_fixture.py — do not edit by hand.
//
// The three samples (Interlagos Practice, Spa Qualify, Sebring Race) plus the
// checked-in trimmed fixture, which is a genuine second session at the same
// layout and class as the Race sample — so the personal-best tests rank two
// real sessions against each other rather than one against an invented one.
library;

import 'package:pace_reader/data/models/models.dart';
import 'package:pace_reader/features/session_library/data/library_entry.dart';

/// One recording: its metadata, its `Lap` rows as
/// `(index, start, end, Lap Time, Last Sector1, Last Sector2)`, its size and
/// its clock-gap count.
class SampleSession {
  const SampleSession({
    required this.path,
    required this.sizeBytes,
    required this.clockGapCount,
    required this.metadata,
    required this.laps,
  });

  final String path;
  final int sizeBytes;
  final int clockGapCount;
  final SessionMetadata metadata;
  final List<(int, double, double?, double?, double?, double?)> laps;

  String get fileName => path.substring(path.lastIndexOf(r'\\') + 1);

  List<Lap> get lapList => [
        for (final (index, start, end, time, s1, s2) in laps)
          Lap(
            index: index,
            startSeconds: start,
            endSeconds: end,
            lapTimeSeconds: time == null || time == 0 ? null : time,
            sectors: SectorTimes.fromCumulative(
              sector1: s1,
              sector2Cumulative: s2,
              lapTimeSeconds: time,
            ),
          ),
      ];

  SessionFacts get facts => SessionFacts(
        metadata: metadata,
        laps: lapList,
        clockGapCount: clockGapCount,
      );

  /// The row the library writes for this file, as if indexed at [indexedAt]
  /// with the given mtime.
  LibraryEntry entry({
    required DateTime indexedAt,
    int modifiedMs = 0,
    DateTime? lastOpenedAt,
  }) =>
      LibraryEntry.derive(
        path: path,
        fileName: fileName,
        kind: LibrarySourceKind.file,
        file: FileFacts(sizeBytes: sizeBytes, modifiedMs: modifiedMs),
        facts: facts,
        now: indexedAt,
        openedAt: lastOpenedAt,
      );
}
"""


def main() -> None:
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out, inputs = sys.argv[1], sys.argv[2:]
    names = ["interlagosPractice", "spaQualify", "sebringRace", "sebringFixture"]
    if len(inputs) != len(names):
        sys.exit(f"expected {len(names)} inputs, in the order of the usage line")
    body = [HEADER]
    for name, path in zip(names, inputs):
        body.append(f"const {name} = {describe(path).strip()};\n")
    body.append(
        "/// All four, in the order above.\n"
        "const sampleSessions = [\n"
        + "".join(f"  {n},\n" for n in names)
        + "];\n"
    )
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(body))


if __name__ == "__main__":
    main()
