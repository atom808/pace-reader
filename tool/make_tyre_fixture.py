#!/usr/bin/env python3
"""Generate a Dart fixture holding a session's tyre and brake channels per lap.

The tyres & brakes view (SPEC.md §8.6) is built on per-lap aggregates of eight
per-corner channels. Its widget and golden tests run under plain `flutter
test`, where `dart_duckdb`'s native library is not linked and no `.duckdb`
file can be opened, so the aggregates have to arrive as Dart source — and they
have to be the *real* ones, from a whole stint: the trimmed fixture holds four
laps, and a wear trend over four laps shows nothing.

The SQL below is `lapStatsSql`'s multi-column form, verbatim in structure (lap
starts become channel row numbers by the integer stride; every channel used
here rides the master grid), and `integration_test/tires_brakes_test.dart`
checks the Dart query against the checked-in fixture lap for lap. The setup
facts the view reads are copied out of `metadata.CarSetup` too — both
`stringValue` and `lastSavedStringValue`, since the view must pick the first.

Checked in for the same reason `make_fixture.py` is: a fixture nobody can
regenerate is an artifact described only in prose. It reads `samples/`, which
is git-ignored, because the point is the full session.

Usage:
    python3 tool/make_tyre_fixture.py \
        "samples/Sebring International Raceway_R_2026-07-07T06_42_17Z.duckdb" \
        test/fixtures/sebring_race_tyres.dart --prefix sebringRace
"""

from __future__ import annotations

import argparse
import json
import sys

try:
    import duckdb
except ImportError:  # pragma: no cover - a setup problem, not a logic one
    sys.exit("needs `pip install duckdb`")

CHANNELS = [
    ("TyresPressure", "Pressure", "kPa, 10 Hz"),
    ("TyresTempLeft", "TreadLeft", "°C, 100 Hz — the car-frame LEFT edge"),
    ("TyresTempCentre", "TreadCentre", "°C, 100 Hz"),
    ("TyresTempRight", "TreadRight", "°C, 100 Hz — the car-frame RIGHT edge"),
    ("TyresCarcassTemp", "Carcass", "°C, 5 Hz"),
    ("TyresRimTemp", "Rim", "°C, 50 Hz"),
    ("Tyres Wear", "Wear", "% remaining, 10 Hz"),
    ("Brakes Temp", "Brakes", "°C, 50 Hz"),
]
COLUMNS = ["value1", "value2", "value3", "value4"]
SETUP_KEYS = [
    f"WM_{group}-W_{corner}"
    for group in ("COMPOUND", "PRESSURE", "CAMBER", "BRAKEDISC")
    for corner in ("FL", "FR", "RL", "RR")
] + ["VM_BRAKE_BALANCE", "VM_BRAKE_MIGRATION", "VM_BRAKE_PRESSURE"]
EVENTS = [("Brake Bias Rear", "value"), ("Brake Migration", "value")]


def lap_stats_sql(channel: str, stride: int) -> str:
    projected = ", ".join(f'"{c}" AS v_{n}' for n, c in enumerate(COLUMNS))
    aggregates = ", ".join(
        f"arg_min(c.v_{n}, c.i), arg_max(c.v_{n}, c.i), "
        f"MIN(c.v_{n}), MAX(c.v_{n}), AVG(c.v_{n})"
        for n in range(len(COLUMNS))
    )
    return (
        'WITH _master AS (SELECT value AS t, (row_number() OVER ()) - 1 AS mi '
        'FROM "GPS Time"), '
        '_laps AS (SELECT "value" AS lap_index, ts AS start_ts FROM "Lap"), '
        "_starts AS (SELECT l.lap_index, m.mi AS m0 FROM _laps l "
        "ASOF JOIN _master m ON l.start_ts <= m.t), "
        f"_bounds AS (SELECT lap_index, CAST(ceil(m0 / {stride}.0) AS BIGINT) "
        "AS c0 FROM _starts), "
        f'_ch AS (SELECT {projected}, (row_number() OVER ()) - 1 AS i FROM "{channel}") '
        f"SELECT b.lap_index, {aggregates}, COUNT(*) "
        "FROM _ch c ASOF JOIN _bounds b ON c.i >= b.c0 "
        "GROUP BY b.lap_index ORDER BY b.lap_index"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source")
    parser.add_argument("output")
    parser.add_argument("--prefix", default="sebringRace")
    args = parser.parse_args()

    con = duckdb.connect(args.source, read_only=True)
    masters = con.sql('SELECT count(*) FROM "GPS Time"').fetchone()[0]
    track, session = (
        con.sql("SELECT value FROM metadata WHERE key = 'TrackName'").fetchone()[0],
        con.sql("SELECT value FROM metadata WHERE key = 'SessionType'").fetchone()[0],
    )

    out = [
        f"// {track} {session}: tyre and brake channels per lap (SPEC.md §8.6).",
        "//",
        "// GENERATED by tool/make_tyre_fixture.py from the full recording in",
        "// samples/ (git-ignored) — do not edit by hand. Each row is",
        "// (corner, lap, first, last, min, max, mean, samples), corner 0..3 =",
        "// value1..value4 = FL, FR, RL, RR (§15.5), to four decimals.",
        "library;",
        "",
        "import 'package:pace_reader/data/models/models.dart';",
        "",
        "typedef _Row = (int, int, double, double, double, double, double, int);",
        "",
        "Map<Corner, List<LapChannelStats>> _corners(List<_Row> rows) => {",
        "      for (final corner in Corner.values)",
        "        corner: [",
        "          for (final (c, lap, first, last, min, max, mean, samples) in rows)",
        "            if (c == corner.index)",
        "              LapChannelStats(",
        "                lapIndex: lap,",
        "                first: first,",
        "                last: last,",
        "                min: min,",
        "                max: max,",
        "                mean: mean,",
        "                samples: samples,",
        "              ),",
        "        ],",
        "    };",
    ]

    for channel, suffix, doc in CHANNELS:
        hz = con.sql(
            f"SELECT frequency FROM channelsList WHERE channelName = '{channel}'"
        ).fetchone()[0]
        stride = 100 // hz
        assert stride * hz == 100, f"{channel} is off the master grid"
        rows = con.sql(lap_stats_sql(channel, stride)).fetchall()
        out += [
            "",
            f"/// `{channel}` ({doc}).",
            f"Map<Corner, List<LapChannelStats>> {args.prefix}{suffix}() => _corners(const [",
        ]
        for n in range(len(COLUMNS)):
            for row in rows:
                lap, samples = row[0], row[-1]
                first, last, lo, hi, mean = row[1 + n * 5: 6 + n * 5]
                out.append(
                    f"      ({n}, {lap}, {first:.4f}, {last:.4f}, {lo:.4f}, "
                    f"{hi:.4f}, {mean:.4f}, {samples}),"
                )
        out.append("    ]);")

    setup = json.loads(
        con.sql("SELECT value FROM metadata WHERE key = 'CarSetup'").fetchone()[0]
    )
    subset = {
        key: {
            "stringValue": setup[key]["stringValue"],
            "lastSavedStringValue": setup[key]["lastSavedStringValue"],
        }
        for key in SETUP_KEYS
        if key in setup
    }
    out += [
        "",
        "/// The setup keys the view reads, copied from `metadata.CarSetup`.",
        f"const {args.prefix}TyreSetupJson = r'''",
        json.dumps(subset, indent=2, ensure_ascii=False),
        "''';",
    ]
    for event, column in EVENTS:
        values = [
            r[0] for r in con.sql(f'SELECT "{column}" FROM "{event}" ORDER BY ts').fetchall()
        ]
        name = args.prefix + event.title().replace(" ", "")
        out += [
            "",
            # Full precision, not four decimals: these are FLOAT settings a
            # display rounds, and 0.4875 must stay the 0.48750001… the file
            # holds or its front share rounds the other way (51.3, not 51.2).
            f"/// `{event}`: every recorded row ({len(values)}), full precision.",
            f"const {name} = <double>[{', '.join(repr(v) for v in values)}];",
        ]
    out.append(f"\n/// Master-grid rows in the source, for the record: {masters}.")

    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
