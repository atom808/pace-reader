#!/usr/bin/env python3
"""Generate a Dart fixture of the incident events in the three real samples.

SPEC.md §8.3 wants a slow lap's cause annotated from `LastImpactMagnitude`,
`Yellow Flag State` and `WheelsDetached`. Those are event tables holding a
handful of rows each, so a whole session's worth fits in a few lines of Dart —
which is what lets a plain `flutter test` (where `dart_duckdb`'s native library
is not linked and no `.duckdb` file can be opened) derive per-lap annotations
from numbers the game actually wrote, rather than from an invented series.

Reads the full samples, not the trimmed fixture: the checked-in fixture stops
at lap 3 and would drop the Race sample's second impact, at 508.1 s. `samples/`
is git-ignored, so this is a tool for whoever holds the samples; the *output*
is what CI sees. Checked in for the same reason `make_lap_fixture.py` is — a
fixture nobody can regenerate is an artifact described only in prose.

Rows are emitted exactly as `TelemetryRepository.readEventWindow` hands them to
`StepSeries.fromRows`: `(ts, value)` pairs where BOOLEAN columns stay `bool` (as
`dart_duckdb` returns them), so the fixture exercises the same coercion the app
does. The Practice and Qualify sessions also carry their lap table — the two
shapes the Race sample lacks (two timed laps; one timed lap and an invalidated
one) — mapped the way `lapTableSql` does: a lap's time and sector splits read at
its *end* boundary, with `0.0` meaning "not recorded" (§8.3.1).

Usage:
    python3 tool/make_incident_fixture.py samples/ test/fixtures/lap_incidents.dart

Needs `pip install duckdb`.
"""

from __future__ import annotations

import glob
import os
import sys

try:
    import duckdb
except ImportError:  # pragma: no cover - a setup problem, not a logic one
    sys.exit("needs `pip install duckdb`")

SESSIONS = [
    # (dart prefix, filename glob, description)
    ("interlagosPractice", "*_P_*.duckdb", "Interlagos, GT3, Practice"),
    ("spaQualify", "*_Q_*.duckdb", "Spa-Francorchamps, Hypercar, Qualify"),
    ("sebringRace", "*_R_*.duckdb", "Sebring School Circuit, GT3, Race"),
]


def num(value: float) -> str:
    """A Python float as a Dart double literal, exactly."""
    return repr(float(value))


def cell(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return num(value)


def rows_of(con, table: str, columns: list[str]) -> str:
    """A `const [...]` of `(ts, v1[, v2, ...])` records for [table]."""
    cols = ", ".join(f'"{c}"' for c in columns)
    rows = con.execute(f'SELECT ts, {cols} FROM "{table}" ORDER BY ts').fetchall()
    body = ", ".join("(" + ", ".join(cell(v) for v in row) + ")" for row in rows)
    return f"const [{body}]"


def laps(con) -> str:
    rows = con.execute(
        '''
        WITH _b AS (
          SELECT value AS lap_index, ts AS start_ts,
                 lead(ts) OVER (ORDER BY ts) AS end_ts FROM "Lap")
        SELECT _b.lap_index, _b.start_ts, _b.end_ts,
               lt.value, s1.value, s2.value
        FROM _b
        LEFT JOIN "Lap Time" lt ON lt.ts = _b.end_ts
        LEFT JOIN "Last Sector1" s1 ON s1.ts = _b.end_ts
        LEFT JOIN "Last Sector2" s2 ON s2.ts = _b.end_ts
        ORDER BY _b.lap_index
        '''
    ).fetchall()

    def opt(v):
        # 0.0 is the game's "not recorded" (§8.3.1), not a zero-second lap.
        return "null" if v is None or v == 0.0 else num(v)

    lines = []
    for idx, start, end, lap, s1, s2 in rows:
        lines.append(
            f"    ({idx}, {num(start)}, {'null' if end is None else num(end)}, "
            f"{opt(lap)}, {opt(s1)}, {opt(s2)}),"
        )
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    samples_dir, out_path = sys.argv[1], sys.argv[2]

    out = [
        "// Generated by tool/make_incident_fixture.py — do not edit by hand.",
        "//",
        "// The incident events of the three real samples (SPEC.md §8.3), exactly as",
        "// `TelemetryRepository.readEventWindow` reads them: every row of",
        "// `LastImpactMagnitude`, `Yellow Flag State` and `WheelsDetached` (four value",
        "// columns), first row included — that one is the state at the start of the",
        "// recording, at the session origin, not a change.",
        "//",
        "// What the samples hold is thin, and that is the finding: `Yellow Flag State`",
        "// and `WheelsDetached` are a single all-zero row in all three, and only the",
        "// Race sample's `LastImpactMagnitude` ever changes.",
        "library;",
        "",
        "import 'package:pace_reader/data/models/models.dart';",
        "",
        "/// One session's incident events, as the repository reads them.",
        "class RecordedIncidentEvents {",
        "  const RecordedIncidentEvents({",
        "    required this.impact,",
        "    required this.yellowFlag,",
        "    required this.wheelsDetached,",
        "  });",
        "",
        "  final StepSeries impact;",
        "  final StepSeries yellowFlag;",
        "",
        "  /// One series per value column: value1..value4, i.e. FL, FR, RL, RR (§15.5).",
        "  final List<StepSeries> wheelsDetached;",
        "}",
        "",
        "StepSeries _series(String name, List<(double, Object?)> rows) =>",
        "    StepSeries.fromRows(rows, eventName: name);",
        "",
        "List<StepSeries> _corners(List<(double, int, int, int, int)> rows) => [",
        "      for (var corner = 0; corner < 4; corner++)",
        "        _series('WheelsDetached', [",
        "          for (final row in rows)",
        "            (row.$1, [row.$2, row.$3, row.$4, row.$5][corner]),",
        "        ]),",
        "    ];",
        "",
        "List<Lap> _lapsFrom(",
        "  List<(int, double, double?, double?, double?, double?)> raw,",
        ") =>",
        "    [",
        "      for (final (index, start, end, time, s1, s2cum) in raw)",
        "        Lap(",
        "          index: index,",
        "          startSeconds: start,",
        "          endSeconds: end,",
        "          lapTimeSeconds: time,",
        "          sectors: SectorTimes.fromCumulative(",
        "            sector1: s1,",
        "            sector2Cumulative: s2cum,",
        "            lapTimeSeconds: time,",
        "          ),",
        "        ),",
        "    ];",
        "",
    ]

    for prefix, pattern, description in SESSIONS:
        matches = sorted(glob.glob(os.path.join(samples_dir, pattern)))
        if len(matches) != 1:
            sys.exit(f"{pattern}: expected exactly one file in {samples_dir}, found {matches}")
        con = duckdb.connect(matches[0], read_only=True)
        origin = con.execute('SELECT min(ts) FROM "Lap"').fetchone()[0]

        out.append(f"// {description} — session origin {origin!r} s.")
        if prefix != "sebringRace":
            # The Race sample's laps live in `sebring_race_per_lap.dart`.
            out.append(f"List<Lap> {prefix}Laps() => _lapsFrom(const [")
            out.append(laps(con))
            out.append("]);")
            out.append("")
        out.append(f"RecordedIncidentEvents {prefix}Incidents() => RecordedIncidentEvents(")
        out.append(
            f"  impact: _series('LastImpactMagnitude', "
            f"{rows_of(con, 'LastImpactMagnitude', ['value'])}),"
        )
        out.append(
            f"  yellowFlag: _series('Yellow Flag State', "
            f"{rows_of(con, 'Yellow Flag State', ['value'])}),"
        )
        out.append(
            f"  wheelsDetached: _corners("
            f"{rows_of(con, 'WheelsDetached', ['value1', 'value2', 'value3', 'value4'])}),"
        )
        out.append(");")
        out.append("")

    with open(out_path, "w") as fh:
        fh.write("\n".join(out))
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
